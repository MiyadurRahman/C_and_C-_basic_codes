#include <iostream>
using namespace std;

int main() {
    cout << "Hello, World!\n"; // Moves to a new line after printing "Hello, World!"
    cout << "This is a tab:\tand this is after the tab.\n";
    cout << "Quotes: \"C++\" is fun!\n";
    cout << "Backslash example: C:\\Program Files\\MyApp\n";
    return 0;
}
/*In the example, \n is used to create new lines, 
\t to insert a tab space, 
\" to print double quotes,
 and \\ to print a backslash.
 */